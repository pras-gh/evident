STREAM_START, STREAM_END = 20.0, 46.0     # % of the pinned range


def stream(html):
    """One span per word, each with its own slice of the scroll range.
    <em>…</em> marks a phrase that keeps a soft glow once revealed."""
    tokens, glow = [], False
    for chunk in re.split(r'(<em>|</em>)', html):
        if chunk == '<em>':   glow = True;  continue
        if chunk == '</em>':  glow = False; continue
        for w in chunk.split():
            tokens.append((w, glow))

    span = (STREAM_END - STREAM_START) / len(tokens)
    out = []
    for i, (word, is_glow) in enumerate(tokens):
        s = STREAM_START + i * span
        e = s + span * 1.6                      # overlap so it reads continuous
        cls = 'w glow' if is_glow else 'w'
        out.append(f'<span class="{cls}" style="animation-range:contain {s:.2f}% '
                   f'contain {min(e, 100):.2f}%">{word}</span>')
    return '\n            '.join(out)


