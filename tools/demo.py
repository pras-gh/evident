"""
Builds section 3 — the evidence demo — and splices it into index.html between
the DEMO markers. The streaming answer is generated as one span per word, each
carrying its own slice of the pinned scroll range, so "streaming" is scrubbed
by the scrollbar rather than played by a timer.

    python3 tools/demo.py
"""
import re, os

